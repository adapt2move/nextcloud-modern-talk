#[cfg(test)]
mod tests {
    use super::*;
    use unicode_segmentation::UnicodeSegmentation;

    #[test]
    fn every_entry_is_one_grapheme_and_unique_within_its_category() {
        for (tab, emojis) in CATEGORIES {
            assert_eq!(tab.graphemes(true).count(), 1, "{tab}");
            let mut seen = std::collections::HashSet::new();
            for emoji in emojis {
                assert_eq!(emoji.graphemes(true).count(), 1, "{emoji}");
                assert!(!emoji.is_ascii(), "{emoji}");
                assert!(seen.insert(*emoji), "duplicate {emoji}");
            }
        }
    }
}
